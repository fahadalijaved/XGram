"""Shapes drawn for the library packs where the library has no icon (used by "drawn" parts of maps/<pack>.json).

DRAWN[pack][name] is SVG markup on the library's own grid, drawn in its style:
  solar     24 grid, bold duotone: the body filled at opacity .5, the details solid; 1.5 strokes, round ends;
            corners are Solar's squircle (see squircle())
  mingcute  24 grid, line: 2 px strokes, round ends and joins
PIXEL[name] is a 24x24 grid for XGram Pixel (Pixelarticons: 2-cell lines, 2x2 steps for diagonals, no curves),
'#' = ink.
"""


def _g(v):
    return ('%.3f' % v).rstrip('0').rstrip('.')


def squircle(x, y, w, h, r):
    """Solar's rounded rectangle: its smooth corner (from check-square, corner size 10) scaled to r."""
    s = r / 10.0
    k = [4.714 * s, 7.071 * s, 8.536 * s, 1.464 * s, 2.929 * s, 5.286 * s]
    x2, y2 = x + w, y + h
    pts = ['M%s %s' % (_g(x + r), _g(y2))]
    pts.append('C%s %s %s %s %s %s' % (_g(x + r - k[0]), _g(y2), _g(x + r - k[1]), _g(y2), _g(x + r - k[2]), _g(y2 - k[3])))
    pts.append('C%s %s %s %s %s %s' % (_g(x), _g(y2 - k[4]), _g(x), _g(y2 - k[5]), _g(x), _g(y2 - r)))
    pts.append('V%s' % _g(y + r))
    pts.append('C%s %s %s %s %s %s' % (_g(x), _g(y + k[5]), _g(x), _g(y + k[4]), _g(x + k[3]), _g(y + k[3])))
    pts.append('C%s %s %s %s %s %s' % (_g(x + k[4]), _g(y), _g(x + k[5]), _g(y), _g(x + r), _g(y)))
    pts.append('H%s' % _g(x2 - r))
    pts.append('C%s %s %s %s %s %s' % (_g(x2 - k[5]), _g(y), _g(x2 - k[4]), _g(y), _g(x2 - k[3]), _g(y + k[3])))
    pts.append('C%s %s %s %s %s %s' % (_g(x2), _g(y + k[4]), _g(x2), _g(y + k[5]), _g(x2), _g(y + r)))
    pts.append('V%s' % _g(y2 - r))
    pts.append('C%s %s %s %s %s %s' % (_g(x2), _g(y2 - k[5]), _g(x2), _g(y2 - k[4]), _g(x2 - k[3]), _g(y2 - k[3])))
    pts.append('C%s %s %s %s %s %s' % (_g(x2 - k[4]), _g(y2), _g(x2 - k[5]), _g(y2), _g(x2 - r), _g(y2)))
    return ''.join(pts) + 'Z'


def _half(d):
    return '<path fill="currentColor" opacity=".5" d="%s"/>' % d


def _solid(d):
    return '<path fill="currentColor" d="%s"/>' % d


def _line(d, w=1.5, opacity=None):
    return '<path fill="none" stroke="currentColor" stroke-width="%s" stroke-linecap="round" stroke-linejoin="round"%s d="%s"/>' % (
        _g(w), ' opacity="%s"' % opacity if opacity else '', d)


def _dot(cx, cy, r=1.5):
    return 'M%s %sa%s %s 0 1 0 %s 0a%s %s 0 1 0 %s 0Z' % (_g(cx - r), _g(cy), _g(r), _g(r), _g(2 * r), _g(r), _g(r), _g(-2 * r))


